// Helper functions
export function getBlogBySlug(slug: string): BlogPost | undefined {
  return mockBlogs.find((blog) => blog.slug === slug);
}

export function getBlogsByCategory(category: BlogCategory): BlogPost[] {
  return mockBlogs.filter((blog) => blog.category === category);
}

export function getFeaturedBlogs(limit: number = 3): BlogPost[] {
  return mockBlogs.filter((blog) => blog.isFeatured).slice(0, limit);
}

export function getLatestBlogs(limit: number = 6): BlogPost[] {
  return [...mockBlogs]
    .sort((a, b) => new Date(b.publishedDate).getTime() - new Date(a.publishedDate).getTime())
    .slice(0, limit);
}

export function getRelatedBlogs(slug: string, limit: number = 3): BlogPost[] {
  const currentBlog = getBlogBySlug(slug);
  if (!currentBlog) return [];

  return mockBlogs
    .filter((blog) => blog.slug !== slug)
    .filter((blog) =>
      blog.category === currentBlog.category ||
      blog.tags.some((tag) => currentBlog.tags.includes(tag))
    )
    .slice(0, limit);
}

export function searchBlogs(query: string): BlogPost[] {
  const lowerQuery = query.toLowerCase();
  return mockBlogs.filter((blog) =>
    blog.title.toLowerCase().includes(lowerQuery) ||
    blog.excerpt.toLowerCase().includes(lowerQuery) ||
    blog.tags.some((tag) => tag.toLowerCase().includes(lowerQuery))
  );
}
